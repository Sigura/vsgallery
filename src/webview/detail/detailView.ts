import type { EntryPatch, GallerySettings, ImageEntry, WebviewToHost } from '../../shared/protocol';
import { parseKohyaFolder } from '../../shared/kohya';
import { parseTags } from '../../shared/captions';
import { ImageViewer, isTyping } from './imageViewer';
import { CaptionEditor } from './captionEditor';
import { applyIcons } from '../icons';
import { ImageEditor, type EditorUiState } from './editor/imageEditor';

export interface DetailHost {
  entry(id: string): ImageEntry | undefined;
  imageUrl(e: ImageEntry): string;
  /** A quickly available small version (thumbnail), if any. */
  previewUrl(e: ImageEntry): string | undefined;
  post(m: WebviewToHost): void;
  settings(): GallerySettings;
  /** Select the shown image in the VS Code Explorer while it changes. */
  syncExplorer(): boolean;
  setSyncExplorer(on: boolean): void;
  /** Tags generated by the WD tagger for the image file (loads the model on first use). */
  generateTags(e: ImageEntry): Promise<string[]>;
  editorState(): Partial<EditorUiState> | undefined;
  saveEditorState(s: EditorUiState): void;
  /** Detail view shows `id` (undefined = closed). */
  changed(id: string | undefined): void;
  /** Detail view closed while showing `id`. */
  closed(id: string | undefined): void;
}

interface Loaded {
  key: string;
  promise: Promise<ImageBitmap>;
}

const versionKey = (e: ImageEntry) => `${e.id}|${e.size}|${e.mtime}`;

function formatBytes(n: number): string {
  if (n < 1024) return `${n} B`;
  if (n < 1048576) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / 1048576).toFixed(2)} MB`;
}

function gcd(a: number, b: number): number {
  return b ? gcd(b, a % b) : a;
}

/** Full-size image view with caption editor and metadata; ←/→ walk the gallery's current order. */
export class DetailView {
  private readonly viewer: ImageViewer;
  private readonly caption: CaptionEditor;
  private readonly imageEditor: ImageEditor;
  private readonly dialog: HTMLDialogElement;
  private order: string[] = [];
  private current: string | undefined;
  private shownVersion: string | undefined;
  private readonly bitmaps = new Map<string, Loaded>();
  private navigating = false;
  /** The original (not just the thumbnail preview) of the current image is on screen. */
  private viewerHasFull = false;
  private noticeTimer: ReturnType<typeof setTimeout> | undefined;
  private generating = false;

  constructor(
    private readonly root: HTMLElement,
    private readonly host: DetailHost,
  ) {
    root.innerHTML = `
      <div class="detail-main">
        <div class="detail-bar">
          <button data-act="back" title="Back to gallery (Esc)">← Gallery</button>
          <button data-act="prev" title="Previous image (←)">‹</button>
          <span class="pos"></span>
          <button data-act="next" title="Next image (→)">›</button>
          <span class="detail-name"></span>
          <span class="spacer"></span>
          <span class="notice" aria-live="polite"></span>
          <button data-act="fit" title="Fit to view (F)">Fit</button>
          <button data-act="actual" title="Actual size (1)">100%</button>
          <span class="zoom"></span>
          <button data-act="sync" data-icon="sync" title="Sync: select the shown image in the VS Code Explorer">Sync</button>
          <button data-act="delete" title="Delete image and caption (Delete)">Delete</button>
        </div>
        <div class="edit-bar"></div>
        <div class="viewer"></div>
      </div>
      <aside class="detail-side">
        <div class="caption-editor"></div>
        <table class="meta"></table>
      </aside>
      <dialog class="leave-dialog">
        <form method="dialog">
          <p class="leave-text"></p>
          <div class="dialog-buttons">
            <button value="save">Save</button>
            <button value="discard">Discard</button>
            <button value="cancel">Cancel</button>
          </div>
        </form>
      </dialog>`;
    this.viewer = new ImageViewer(root.querySelector('.viewer')!);
    this.viewer.onZoom = (s) => {
      root.querySelector('.zoom')!.textContent = `${Math.round(s * 100)}%`;
      this.imageEditor?.zoomChanged();
    };
    this.imageEditor = new ImageEditor(root.querySelector('.edit-bar')!, this.viewer, {
      post: (m) => host.post(m),
      settings: () => host.settings(),
      state: () => host.editorState(),
      saveState: (s) => host.saveEditorState(s),
      notice: (t) => this.notice(t),
      changed: () => root.querySelector('.detail-name')!.classList.toggle('dirty', this.imageEditor?.dirty ?? false),
    });
    this.caption = new CaptionEditor(
      root.querySelector('.caption-editor')!,
      {
        save: (id, text) => host.post({ type: 'saveCaption', id, text }),
        autosave: () => ({ enabled: host.settings().captionAutosave, delay: host.settings().captionAutosaveDelay }),
        generate: () => void this.generate(),
      },
    );
    applyIcons(root.querySelector('.detail-bar')!);
    this.dialog = root.querySelector('.leave-dialog')!;
    root.querySelector('.detail-bar')!.addEventListener('click', (e) => {
      const act = (e.target as HTMLElement).closest<HTMLElement>('[data-act]')?.dataset.act;
      if (act) this.action(act);
    });
    window.addEventListener('keydown', (e) => this.onKey(e));
  }

  get isOpen(): boolean {
    return !this.root.hidden;
  }

  open(id: string, order: string[]): void {
    this.order = order.includes(id) ? [...order] : [id, ...order];
    this.root.hidden = false;
    document.body.classList.add('detail-open');
    void this.show(id);
    this.viewer.canvas.focus({ preventScroll: true });
  }

  async close(): Promise<void> {
    if (!this.isOpen || !(await this.confirmLeave())) return;
    const id = this.current;
    this.root.hidden = true;
    document.body.classList.remove('detail-open');
    this.current = undefined;
    this.shownVersion = undefined;
    this.imageEditor.unload();
    this.viewer.setImage(undefined);
    this.evict(new Set());
    this.host.changed(undefined);
    this.host.closed(id);
  }

  onEntriesChanged(upserts: readonly ImageEntry[], removed: readonly string[]): void {
    if (!this.isOpen) return;
    if (removed.length) {
      const gone = new Set(removed);
      const cur = this.current;
      const idx = cur ? this.order.indexOf(cur) : -1;
      this.order = this.order.filter((id) => !gone.has(id));
      if (cur && gone.has(cur)) {
        this.caption.discard();
        const next = this.order[Math.min(idx, this.order.length - 1)];
        if (next) void this.show(next);
        else void this.close();
        return;
      }
    }
    const cur = this.current && upserts.find((e) => e.id === this.current);
    if (cur) {
      this.renderMeta(cur);
      if (versionKey(cur) !== this.shownVersion) {
        if (this.imageEditor.expectsWrite(cur.id)) {
          // Our own save: the edited pixels on screen already are the new file.
          this.shownVersion = versionKey(cur);
        } else if (this.imageEditor.dirty) {
          this.notice('The image file changed on disk. Saving will overwrite that change.');
        } else {
          void this.showImage(cur);
        }
      }
    }
    this.renderPosition();
  }

  onPatch(p: EntryPatch): void {
    if (!this.isOpen || p.id !== this.current) return;
    const e = this.host.entry(p.id);
    if (p.caption !== undefined) this.caption.external(p.id, p.caption);
    if (e) this.renderMeta(e);
  }

  onImageSaved(id: string, mode: 'overwrite' | 'copy', newId: string | undefined, error: string | undefined): void {
    this.imageEditor.saved(id, mode, newId, error);
    if (!error && newId && mode === 'copy' && this.current) {
      const i = this.order.indexOf(this.current);
      if (!this.order.includes(newId)) this.order.splice(i + 1, 0, newId);
      this.renderPosition();
    }
  }

  onCaptionSaved(id: string, text: string, error: string | undefined): void {
    if (error && id !== this.caption.currentId) this.notice(`Saving caption of ${id} failed: ${error}`);
    this.caption.saved(id, text, error);
    const e = this.host.entry(id);
    if (e && id === this.current) this.renderMeta(e);
  }

  /** Progress text of the tagger (model download/loading); shown while the detail view is open. */
  taggerStatus(text: string): void {
    if (this.isOpen && text) this.notice(text);
  }

  private async generate(): Promise<void> {
    const id = this.current;
    const e = id ? this.host.entry(id) : undefined;
    if (!id || !e || this.generating) return;
    this.generating = true;
    this.caption.setGenerating(true);
    try {
      const tags = await this.host.generateTags(e);
      const t = this.host.settings().tagger;
      if (this.current === id) {
        this.caption.applyGenerated(id, tags, t.existingCaptions, t.triggerWord);
        this.notice(`Generated ${tags.length} tag${tags.length === 1 ? '' : 's'}`);
      }
    } catch (err) {
      this.notice(`Generating tags failed: ${err instanceof Error ? err.message : err}`);
    } finally {
      this.generating = false;
      this.caption.setGenerating(false);
    }
  }

  private renderSync(): void {
    const on = this.host.syncExplorer();
    const btn = this.root.querySelector<HTMLElement>('[data-act="sync"]')!;
    btn.classList.toggle('on', on);
    btn.setAttribute('aria-pressed', String(on));
  }

  private action(act: string): void {
    switch (act) {
      case 'back':
        void this.close();
        return;
      case 'prev':
        void this.go(-1);
        return;
      case 'next':
        void this.go(1);
        return;
      case 'fit':
        this.viewer.fit();
        return;
      case 'actual':
        this.viewer.actualSize();
        return;
      case 'delete':
        if (this.current) this.host.post({ type: 'delete', ids: [this.current] });
        return;
      case 'sync': {
        const on = !this.host.syncExplorer();
        this.host.setSyncExplorer(on);
        this.renderSync();
        if (on && this.current) this.host.post({ type: 'revealInExplorer', id: this.current });
        return;
      }
    }
  }

  private onKey(e: KeyboardEvent): void {
    if (!this.isOpen || this.dialog.open) return;
    const ctrl = e.ctrlKey || e.metaKey;
    if (ctrl && e.key.toLowerCase() === 's') {
      e.preventDefault();
      this.caption.saveNow();
      if (this.imageEditor.dirty) void this.imageEditor.save('overwrite');
      return;
    }
    if (isTyping(e.target)) {
      if (e.key === 'Escape') (e.target as HTMLElement).blur();
      return;
    }
    if (this.imageEditor.handleKey(e)) {
      e.preventDefault();
      return;
    }
    if (ctrl || e.altKey) return;
    const keys: Record<string, () => void> = {
      ArrowLeft: () => void this.go(-1),
      ArrowRight: () => void this.go(1),
      Escape: () => void this.close(),
      Delete: () => this.action('delete'),
      f: () => this.viewer.fit(),
      '0': () => this.viewer.fit(),
      '1': () => this.viewer.actualSize(),
      '+': () => this.viewer.zoomBy(1.25),
      '=': () => this.viewer.zoomBy(1.25),
      '-': () => this.viewer.zoomBy(0.8),
      Enter: () => this.caption.focus(),
      g: () => void this.generate(),
    };
    const fn = keys[e.key];
    if (!fn) return;
    e.preventDefault();
    fn();
  }

  private async go(delta: number): Promise<void> {
    if (this.navigating || !this.current) return;
    const i = this.order.indexOf(this.current);
    const next = this.order[i + delta];
    if (!next) return;
    this.navigating = true;
    try {
      if (await this.confirmLeave()) await this.show(next);
    } finally {
      this.navigating = false;
    }
  }

  /** Autosaves the caption; asks about unsaved image edits (never autosaved) or a caption that cannot autosave. */
  private async confirmLeave(): Promise<boolean> {
    const captionDone = this.caption.flushForLeave();
    const imageDirty = this.imageEditor.dirty;
    if (captionDone && !imageDirty) return true;
    const parts = [!captionDone && 'the caption', imageDirty && 'the image'].filter(Boolean).join(' and ');
    this.root.querySelector('.leave-text')!.textContent = `There are unsaved changes to ${parts}.`;
    this.dialog.returnValue = '';
    this.dialog.showModal();
    await new Promise<void>((resolve) => this.dialog.addEventListener('close', () => resolve(), { once: true }));
    const v = this.dialog.returnValue;
    if (v === 'save') {
      if (!captionDone) this.caption.saveKeepingMine();
      if (imageDirty) await this.imageEditor.save('overwrite');
      return true;
    }
    if (v === 'discard') {
      if (!captionDone) this.caption.discard();
      if (imageDirty) this.imageEditor.discard();
      return true;
    }
    return false;
  }

  private async show(id: string): Promise<void> {
    this.imageEditor.unload();
    this.current = id;
    this.host.changed(id);
    const e = this.host.entry(id);
    this.renderPosition();
    this.renderSync();
    if (e && this.host.syncExplorer()) this.host.post({ type: 'revealInExplorer', id });
    if (!e) {
      this.root.querySelector('.detail-name')!.textContent = id;
      this.viewer.showMessage('This image no longer exists.');
      return;
    }
    this.root.querySelector('.detail-name')!.textContent = e.id;
    this.caption.load(id, e.caption, e.captionFile ? e.captionFile.slice(e.captionFile.lastIndexOf('/') + 1) : '(created on save)');
    this.renderMeta(e);
    await this.showImage(e);
  }

  private async showImage(e: ImageEntry): Promise<void> {
    const version = versionKey(e);
    this.shownVersion = version;
    const loaded = this.bitmaps.get(e.id);
    if (!loaded || loaded.key !== version) {
      const preview = this.host.previewUrl(e);
      if (preview && e.w && e.h) {
        const img = new Image();
        img.src = preview;
        img.decode().then(
          () => {
            if (this.shownVersion === version && !this.viewerHasFull) this.viewer.setImage(img, e.w, e.h);
          },
          () => undefined,
        );
      } else {
        this.viewer.showMessage('Loading…');
      }
    }
    this.viewerHasFull = false;
    this.preloadAround(e.id);
    try {
      const bmp = await this.load(e);
      if (this.shownVersion !== version) return;
      this.viewerHasFull = true;
      this.imageEditor.load(e.id, e.name, bmp);
    } catch (err) {
      if (this.shownVersion === version) this.viewer.showMessage(`Cannot load image: ${err instanceof Error ? err.message : err}`);
    }
  }

  private load(e: ImageEntry): Promise<ImageBitmap> {
    const key = versionKey(e);
    const cached = this.bitmaps.get(e.id);
    if (cached?.key === key) return cached.promise;
    if (cached) cached.promise.then((b) => b.close(), () => undefined);
    const promise = fetch(this.host.imageUrl(e))
      .then((res) => {
        if (!res.ok) throw new Error(res.status === 404 ? 'file not found' : `HTTP ${res.status}`);
        return res.blob();
      })
      .then((blob) => createImageBitmap(blob));
    this.bitmaps.set(e.id, { key, promise });
    promise.catch(() => {
      if (this.bitmaps.get(e.id)?.promise === promise) this.bitmaps.delete(e.id);
    });
    return promise;
  }

  /** Keeps the current image and its neighbours decoded; frees everything else. */
  private preloadAround(id: string): void {
    const i = this.order.indexOf(id);
    const keep = new Set([id, this.order[i - 1], this.order[i + 1]].filter((x): x is string => !!x));
    this.evict(keep);
    for (const n of keep) {
      const e = this.host.entry(n);
      if (e && n !== id) this.load(e).catch(() => undefined);
    }
  }

  private evict(keep: ReadonlySet<string>): void {
    for (const [id, l] of this.bitmaps) {
      if (keep.has(id)) continue;
      this.bitmaps.delete(id);
      l.promise.then((b) => b.close(), () => undefined);
    }
  }

  private renderPosition(): void {
    const i = this.current ? this.order.indexOf(this.current) : -1;
    this.root.querySelector('.pos')!.textContent = i >= 0 ? `${i + 1} / ${this.order.length}` : '';
    this.root.querySelector<HTMLButtonElement>('[data-act="prev"]')!.disabled = i <= 0;
    this.root.querySelector<HTMLButtonElement>('[data-act="next"]')!.disabled = i < 0 || i >= this.order.length - 1;
  }

  private renderMeta(e: ImageEntry): void {
    const rows: [string, string][] = [['File', e.id]];
    if (e.dir) {
      const seg = e.dir.slice(e.dir.lastIndexOf('/') + 1);
      const { label, repeats } = parseKohyaFolder(seg);
      rows.push(['Folder', repeats === undefined ? e.dir : `${label} (${repeats} repeats)`]);
    }
    if (e.w && e.h) {
      const g = gcd(e.w, e.h);
      const div8 = e.w % 8 === 0 && e.h % 8 === 0;
      const div64 = e.w % 64 === 0 && e.h % 64 === 0;
      rows.push(
        ['Resolution', `${e.w} × ${e.h} (${((e.w * e.h) / 1e6).toFixed(2)} MP)`],
        ['Aspect', `${(e.w / e.h).toFixed(3)} (${e.w / g}:${e.h / g})`],
        ['Divisible', `÷8 ${div8 ? '✓' : '✗'}   ÷64 ${div64 ? '✓' : '✗'}`],
      );
    }
    rows.push(['File size', formatBytes(e.size)], ['Modified', new Date(e.mtime).toLocaleString()]);
    if (typeof e.caption === 'string') rows.push(['Caption', `${parseTags(e.caption).length} tags, ${e.caption.length} chars`]);
    const table = this.root.querySelector('.meta')!;
    table.replaceChildren(
      ...rows.map(([k, v]) => {
        const tr = document.createElement('tr');
        const th = document.createElement('th');
        th.textContent = k;
        const td = document.createElement('td');
        td.textContent = v;
        tr.append(th, td);
        return tr;
      }),
    );
  }

  private notice(text: string): void {
    const el = this.root.querySelector('.notice')!;
    el.textContent = text;
    clearTimeout(this.noticeTimer);
    this.noticeTimer = setTimeout(() => (el.textContent = ''), 8000);
  }
}
